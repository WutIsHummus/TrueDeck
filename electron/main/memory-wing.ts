/**
 * MemPalace wing names must be unique per project *path*, not just folder name.
 * Otherwise C:\SPTS and C:\Users\…\SPTS both become wing "spts" and share memory.
 */
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { basename, join } from 'path'
import { createHash } from 'crypto'

/** Stable short id from absolute path (Windows-insensitive). */
function pathHash(projectRoot: string): string {
  const norm = projectRoot
    .replace(/\//g, '\\')
    .replace(/[\\/]+$/, '')
    .toLowerCase()
  return createHash('sha256').update(norm).digest('hex').slice(0, 8)
}

/**
 * Wing for MemPalace mine / wake-up / env.
 * Example: `spts-a1b2c3d4` for two different SPTS checkouts.
 */
function wingBase(projectRoot: string): string {
  return (
    basename(projectRoot || '')
      .toLowerCase()
      .replace(/[^a-z0-9_-]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'project'
  )
}

export function wingName(projectRoot: string): string {
  const base = wingBase(projectRoot)
  if (!projectRoot) return base
  return `${base}-${pathHash(projectRoot)}`
}

/**
 * Write mempalace.yaml so a bare `mempalace mine` uses the same per-checkout
 * wing as TrueDeck. The file is machine-specific, so it is gitignored.
 * A yaml that still uses the folder name alone is rewritten; a custom wing is left alone.
 */
export function ensureCheckoutWingFile(projectRoot: string): void {
  if (!projectRoot || !existsSync(projectRoot)) return
  const wing = wingName(projectRoot)
  const yamlPath = join(projectRoot, 'mempalace.yaml')
  const body = [
    '# Generated by TrueDeck. Unique to this checkout path. Do not commit.',
    `wing: ${wing}`,
    'rooms:',
    '  - name: general',
    '    description: Project files for this checkout',
    '    keywords:',
    '      - general',
    ''
  ].join('\n')
  if (!existsSync(yamlPath)) {
    writeFileSync(yamlPath, body, 'utf8')
  } else {
    const cur = readFileSync(yamlPath, 'utf8')
    const found = /^wing:\s*(\S+)/m.exec(cur)
    const current = found?.[1] || ''
    const folder = wingBase(projectRoot)
    const colliding = new Set([folder, folder.replace(/-/g, '_'), '.memory'])
    if (current !== wing && colliding.has(current)) {
      writeFileSync(yamlPath, cur.replace(/^wing:\s*\S+/m, `wing: ${wing}`), 'utf8')
    }
  }
  const git = join(projectRoot, '.git')
  const ignorePath = join(projectRoot, '.gitignore')
  if (!existsSync(git)) return
  const existing = existsSync(ignorePath) ? readFileSync(ignorePath, 'utf8') : ''
  const lines = new Set(existing.split(/\r?\n/).map((line) => line.trim()))
  const missing = ['mempalace.yaml', 'entities.json'].filter((name) => !lines.has(name))
  if (!missing.length) return
  const prefix = !existing || existing.endsWith('\n') ? '' : '\n'
  writeFileSync(
    ignorePath,
    existing + prefix + '\n# MemPalace per-project files\n' + missing.join('\n') + '\n',
    'utf8'
  )
}
